// Renders docs/compliance-matrix.md from Requirement concepts in the core bundle.
// Usage: node scripts/gen-compliance-matrix.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, walk, parseDoc, extractLinks } from './lib/okf.mjs';

const bundle = path.join(ROOT, 'knowledge');
const out = path.join(ROOT, 'docs', 'compliance-matrix.md');
const list = (v) => (v == null ? [] : Array.isArray(v) ? v : [v]);

const rows = walk(path.join(bundle, 'requirements')).files
  .filter((f) => path.basename(f) !== 'index.md' && path.basename(f) !== 'log.md')
  .map((f) => ({ ...parseDoc(f), file: f }))
  .filter((d) => d.fm?.type === 'Requirement')
  .sort((a, b) => a.fm.req_id.localeCompare(b.fm.req_id));

const standards = (body) => [...new Set(extractLinks(body).filter((l) => l.startsWith('/standards/')).map((l) => path.basename(l, '.md')))];

let md = `<!-- Generated by scripts/gen-compliance-matrix.mjs from knowledge/requirements. Do not edit by hand. -->\n\n`;
md += `# Compliance matrix\n\nOne row per requirement. Source of truth is the requirement concept files.\n\n`;
md += `| ID | Requirement | Status | Verification | Modules | Standards | Tests |\n|---|---|---|---|---|---|---|\n`;
for (const r of rows) {
  const f = r.fm;
  md += `| ${f.req_id} | ${f.title} | ${f.status} | ${f.verification} | ${list(f.modules).join(', ')} | ${standards(r.body).join(', ') || '-'} | ${list(f.tests).map((t) => `\`${t}\``).join(', ') || '-'} |\n`;
}
md += `\n${rows.length} requirements.\n`;

if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== md) {
    console.error('docs/compliance-matrix.md is stale; run `npm run docs:matrix`');
    process.exit(1);
  }
  console.log('compliance matrix up to date');
} else {
  fs.writeFileSync(out, md);
  console.log(`wrote docs/compliance-matrix.md (${rows.length} requirements)`);
}
